import { isAbsolute, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Teacher-owned configuration. Shared `config/env.ts` is intentionally not modified. */
export interface TeacherConfig {
  readonly nodeEnv: 'development' | 'test' | 'production';
  readonly passwordHash: string | null;
  readonly sessionSecret: string | null;
  readonly allowedOrigins: readonly string[];
  /** Absolute path outside the repository, or null when Google Sheets is not configured. */
  readonly serviceAccountKeyFile: string | null;
  /** True when Teacher login can work (hash and session secret present). */
  readonly configured: boolean;
}

export const TEACHER_DEFAULT_DEV_ORIGINS: readonly string[] = ['http://127.0.0.1:5173', 'http://localhost:5173'];
export const TEACHER_SESSION_SECRET_MIN_BYTES = 32;

const SCRYPT_HASH_PATTERN = /^scrypt\$\d+\$\d+\$\d+\$[A-Za-z0-9+/=_-]+\$[A-Za-z0-9+/=_-]+$/;

/** apps/server/{src|dist}/modules/teacher/ → repository root (falls back to cwd outside a file: module URL). */
export function defaultRepositoryRoot(): string {
  const url = new URL('../../../../../', import.meta.url);
  return url.protocol === 'file:' ? fileURLToPath(url) : process.cwd();
}

export function parseTeacherConfig(
  source: NodeJS.ProcessEnv | Record<string, string | undefined> = process.env,
  repositoryRoot: string = defaultRepositoryRoot(),
): TeacherConfig {
  const nodeEnv = source.NODE_ENV ?? 'development';
  if (nodeEnv !== 'development' && nodeEnv !== 'test' && nodeEnv !== 'production') {
    throw new Error('NODE_ENV must be development, test, or production.');
  }
  const production = nodeEnv === 'production';

  const passwordHash = source.TEACHER_PASSWORD_HASH?.trim() || null;
  if (passwordHash !== null && !SCRYPT_HASH_PATTERN.test(passwordHash)) {
    throw new Error('TEACHER_PASSWORD_HASH must be generated by `npm run teacher:hash-password` (scrypt format).');
  }

  const sessionSecret = source.TEACHER_SESSION_SECRET?.trim() || null;
  if (sessionSecret !== null && Buffer.byteLength(sessionSecret, 'utf8') < TEACHER_SESSION_SECRET_MIN_BYTES) {
    throw new Error(`TEACHER_SESSION_SECRET must contain at least ${TEACHER_SESSION_SECRET_MIN_BYTES} random bytes.`);
  }

  if (production && passwordHash === null) throw new Error('TEACHER_PASSWORD_HASH is required in production.');
  if (production && sessionSecret === null) throw new Error('TEACHER_SESSION_SECRET is required in production.');

  const allowedOrigins = parseOrigins(source.TEACHER_ALLOWED_ORIGINS, production);
  const serviceAccountKeyFile = parseKeyFile(source.GOOGLE_SERVICE_ACCOUNT_KEY_FILE, repositoryRoot);

  return {
    nodeEnv,
    passwordHash,
    sessionSecret,
    allowedOrigins,
    serviceAccountKeyFile,
    configured: passwordHash !== null && sessionSecret !== null,
  };
}

function parseOrigins(raw: string | undefined, production: boolean): string[] {
  if (raw === undefined) {
    if (production) throw new Error('TEACHER_ALLOWED_ORIGINS is required in production.');
    return [...TEACHER_DEFAULT_DEV_ORIGINS];
  }
  const values = raw.split(',').map((origin) => origin.trim());
  const invalid = () => new Error('TEACHER_ALLOWED_ORIGINS must contain exact, unique HTTP(S) origins.');
  if (values.length === 0 || values.some((origin) => !origin || origin === 'null')) throw invalid();
  for (const origin of values) {
    let parsed: URL;
    try { parsed = new URL(origin); } catch { throw invalid(); }
    if ((parsed.protocol !== 'http:' && parsed.protocol !== 'https:') || parsed.origin !== origin) throw invalid();
  }
  if (new Set(values).size !== values.length) throw invalid();
  return values;
}

function parseKeyFile(raw: string | undefined, repositoryRoot: string): string | null {
  const value = raw?.trim();
  if (!value) return null;
  const keyPath = resolve(repositoryRoot, value);
  if (isInside(repositoryRoot, keyPath)) {
    throw new Error('GOOGLE_SERVICE_ACCOUNT_KEY_FILE must point to a file outside the repository.');
  }
  return keyPath;
}

function isInside(root: string, candidate: string): boolean {
  const normalize = (path: string) => (process.platform === 'win32' ? path.toLowerCase() : path);
  const fromRoot = relative(normalize(resolve(root)), normalize(candidate));
  return fromRoot === '' || (!fromRoot.startsWith('..') && !isAbsolute(fromRoot));
}
